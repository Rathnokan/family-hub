// Tiny pre-build step: writes src/build-id.js with the current timestamp.
// The stub imports BUILD_ID and appends it to the body bundle URL so every
// dev build cache-busts the browser's cached body — without us having to
// touch the release VERSION constant in constants.js.
import { writeFileSync } from "node:fs";
const t = Date.now();
writeFileSync(
    "src/build-id.js",
    `// Auto-generated by gen-build-id.mjs — do not edit.\nexport const BUILD_ID = "${t}";\n`,
);
console.log(`[gen-build-id] BUILD_ID=${t}`);
